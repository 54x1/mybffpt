import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const require = createRequire(import.meta.url);
const checker = require('license-checker-rseidelsohn');
const root = process.cwd();
const checkOnly = process.argv.includes('--check');

// Platform-native optional binaries (one variant per OS/CPU) resolve differently
// depending on which platform `npm install` runs on, which would make this file
// non-reproducible across contributors' machines and CI. None of them ship in
// the distributed browser bundle, so they're excluded from the report.
const platformNativePattern = /^(@rolldown\/binding-|lightningcss-(?:android|darwin|freebsd|linux|win32)|fsevents$)/;

const reviewedLicenses = new Set([
  'AGPL-3.0-or-later',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'BlueOak-1.0.0',
  'CC-BY-3.0',
  'CC-BY-4.0',
  'CC0-1.0',
  'ISC',
  'MIT',
  'MIT-0',
  'MPL-2.0',
  'Unlicense',
  '(MIT AND CC-BY-3.0)',
]);

function scan(production) {
  return new Promise((resolveScan, reject) => {
    checker.init({ start: root, production, excludePrivatePackages: true }, (error, packages) => {
      if (error) reject(error);
      else resolveScan(packages);
    });
  });
}

function rows(packages) {
  return Object.entries(packages)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, info]) => ({
      name,
      license: String(info.licenses ?? 'UNKNOWN'),
      repository: String(info.repository ?? info.url ?? ''),
      licenseFile: info.licenseFile,
    }));
}

function assertReviewed(entries) {
  const unknown = entries.filter(({ license }) => !reviewedLicenses.has(license));
  if (unknown.length) {
    throw new Error(`Unreviewed dependency license(s):\n${unknown.map((p) => `  ${p.name}: ${p.license}`).join('\n')}`);
  }
}

function table(entries) {
  return [
    '| Package | License | Repository |',
    '|---|---|---|',
    ...entries.map(({ name, license, repository }) =>
      `| ${name.replaceAll('|', '\\|')} | ${license.replaceAll('|', '\\|')} | ${repository ? `<${repository}>` : 'Not declared'} |`),
  ].join('\n');
}

function licenseSections(entries) {
  const groups = new Map();
  for (const entry of entries) {
    if (!entry.licenseFile) throw new Error(`No license file found for production dependency ${entry.name}`);
    const text = readFileSync(entry.licenseFile, 'utf8').replaceAll('\r\n', '\n').trim();
    if (!text) throw new Error(`Empty license file for production dependency ${entry.name}`);
    const key = `${entry.license}\0${text}`;
    const group = groups.get(key) ?? { license: entry.license, text, packages: [] };
    group.packages.push(entry.name);
    groups.set(key, group);
  }

  return [...groups.values()]
    .sort((a, b) => a.license.localeCompare(b.license) || a.packages[0].localeCompare(b.packages[0]))
    .map((group) => [
      `## ${group.license}: ${group.packages.join(', ')}`,
      '',
      '```text',
      group.text.replaceAll('```', '` ` `'),
      '```',
    ].join('\n'))
    .join('\n\n');
}

const [allPackages, productionPackages] = await Promise.all([scan(false), scan(true)]);
const all = rows(allPackages).filter(({ name }) => !platformNativePattern.test(name));
const production = rows(productionPackages).filter(({ name }) => !name.startsWith('mybffpt@') && !platformNativePattern.test(name));
const productionNames = new Set(production.map(({ name }) => name));
const developmentOnly = all.filter(({ name }) => !productionNames.has(name) && !name.startsWith('mybffpt@'));
assertReviewed(all);

const markdown = `# Third-Party Software Notices

This file is generated by \`npm run license:notices\`. Do not edit it manually.

mybffpt is licensed under AGPL-3.0-or-later. The packages listed below remain
under their respective licenses. Inclusion here does not relicense them under
the AGPL. The production section records software included in, or used to
produce, the distributed browser application. Development-only packages are
not part of the production distribution.

## Production dependency inventory

${table(production)}

## Development-only dependency inventory

${table(developmentOnly)}

# License texts for production dependencies

${licenseSections(production)}
`;

const releaseText = markdown
  .replace(/^# Third-Party Software Notices/m, 'THIRD-PARTY SOFTWARE NOTICES')
  .replace(/^# License texts for production dependencies/m, 'LICENSE TEXTS FOR PRODUCTION DEPENDENCIES')
  .replace(/^## /gm, '\n---\n');

const outputs = [
  [resolve(root, 'THIRD_PARTY_LICENSES.md'), markdown],
  [resolve(root, 'public', 'THIRD_PARTY_LICENSES.txt'), releaseText],
];

let stale = false;
for (const [file, content] of outputs) {
  if (checkOnly) {
    let current = '';
    try { current = readFileSync(file, 'utf8'); } catch {}
    if (current !== content) {
      console.error(`${file} is missing or stale; run npm run license:notices`);
      stale = true;
    }
  } else {
    writeFileSync(file, content, 'utf8');
    console.log(`Wrote ${file}`);
  }
}

if (stale) process.exit(1);
if (checkOnly) console.log(`Third-party notice check passed (${all.length - 1} dependencies reviewed).`);
